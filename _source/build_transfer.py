#!/usr/bin/env python3
"""Strictly convert human-reviewed case data into a static offline-friendly JS payload."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'_source/transfer_cases.json'
bank=json.loads(source.read_text(encoding='utf8'))
topics=['matrix','gauss','permutations','det','inverse','rank','systems','advanced']
assert set(bank)==set(topics),set(bank)
seen=set()
for topic in topics:
    assert len(bank[topic])>=3,(topic,len(bank[topic]))
    for case in bank[topic]:
        assert case['id'] not in seen,case['id']
        seen.add(case['id'])
        assert case['title'] and case['task'] and case['reason']
        assert case['visual'] and case['fields']
        assert len({f['id'] for f in case['fields']})==len(case['fields'])
        for field in case['fields']:
            assert field['answer']!=''
            if field.get('type')=='choice':
                assert field['answer'] in [x[0] for x in field['options']]
payload="// Generated by _source/build_transfer.py; do not edit manually.\n"
payload+="window.AlgebraTransferBank="+json.dumps(bank,ensure_ascii=False,separators=(',',':'))+";\n"
(ROOT/'assets/transfer-cases.js').write_text(payload,encoding='utf8')
print('TRANSFER_BANK',len(seen),'cases',len(bank),'topics')
